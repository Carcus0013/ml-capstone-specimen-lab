"""Write reports/model_comparison/summary.md from the saved result files.

Run from the project root after the notebooks:  python -m src.summarize_results
The README's results tables are copied from this generated file, so every number in the
documentation traces back to reports/results/.
"""
import pandas as pd

from src import config
from src.utils import ensure_dir, load_json


def _table(df, floatfmt):
    """Minimal Markdown table writer (avoids an extra dependency on `tabulate`)."""
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, row in df.iterrows():
        cells = [("n/a" if pd.isna(v) else floatfmt(v)) if isinstance(v, float) else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    res = config.RESULTS_DIR
    reg = pd.read_csv(res / "regression_results.csv")
    clf = pd.read_csv(res / "classification_results.csv")
    clu = pd.read_csv(res / "clustering_results.csv")
    reg_sel = load_json(config.MODELS_DIR / "regression" / "selection.json")
    clf_sel = load_json(config.MODELS_DIR / "classification" / "selection.json")
    clu_sum = load_json(config.MODELS_DIR / "clustering" / "clustering_summary.json")

    f4 = lambda v: f"{v:.4f}"
    parts = [
        "# Model comparison summary",
        "",
        "Generated by `python -m src.summarize_results` from `reports/results/`. Do not edit by hand.",
        "",
        "## Regression (banana `quality_score`, 200-row held-out test set)",
        "",
        _table(reg[["Rank", "Model", "Test R2", "Test RMSE", "Test MAE", "CV R2 (5-fold, train)", "Best params"]]
               .fillna({"CV R2 (5-fold, train)": float("nan")}), f4),
        "",
        f"Selected: **{reg_sel['selected_model']}** ({reg_sel['rule']}); 5-fold CV R2 "
        f"{reg_sel['cv']['mean']:.5f} ± {reg_sel['cv']['std']:.5f}.",
        "",
        "## Classification (mushroom `class`, 1,625-row stratified held-out test set)",
        "",
        _table(clf[["Rank", "Model", "Accuracy", "Precision", "Recall", "F1 (weighted)", "ROC-AUC",
                    "Poisonous predicted edible"]], f4),
        "",
        f"Selected: **{clf_sel['selected_model']}** ({clf_sel['rule']}).",
        "",
        "## Clustering (cleaned meteorite records)",
        "",
        _table(clu[["Algorithm", "Evaluated on", "Silhouette", "Davies-Bouldin", "Calinski-Harabasz", "n_clusters"]],
               lambda v: f"{v:.4f}" if abs(v) < 100 else f"{v:,.0f}"),
        "",
        f"k = {clu_sum['k']} (votes {clu_sum['k_votes']}); agglomerative linkage = {clu_sum['linkage']}; "
        f"K-Means vs agglomerative ARI = {clu_sum['kmeans_vs_agglomerative_ari']:.3f}; "
        f"bootstrap stability ARI = {clu_sum['stability']['bootstrap_ari_mean']:.4f}.",
        "",
    ]
    out = ensure_dir(config.COMPARISON_DIR) / "summary.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"Wrote {out.relative_to(config.PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
